"""
Конфигурация бота-кликера для Telegram Mini App игры.

Содержит таблицу уровней (кэф, ячейки) и настройки по умолчанию.
"""

# Таблица уровней: номер -> (кэф, количество ячеек)
LEVELS = {
    1:  (1.02,  6),
    2:  (1.27,  5),
    3:  (1.70,  4),
    4:  (2.55,  3),
    5:  (3.40,  4),
    6:  (4.25,  5),
    7:  (5.10,  6),
    8:  (6.38,  5),
    9:  (8.59,  4),
    10: (12.75, 3),
    11: (21.25, 5),
    12: (25.50, 6),
}

MAX_LEVEL = max(LEVELS.keys())

# Типы линий (пресеты калибровки)
LINE_LEFT = "left"      # левая линия
LINE_RIGHT = "right"    # правая линия
LINE_MANUAL = "manual"  # ручная калибровка

LINE_NAMES = {
    LINE_LEFT: "Левая линия",
    LINE_RIGHT: "Правая линия",
    LINE_MANUAL: "Ручная калибровка",
}

# Задержка между кликами уровней в секундах (по умолчанию)
DEFAULT_STEP_DELAY = 0.8

# ---- Стратегия ставок (мартингейл-подобная) ----
# Играем сериями по низкой ставке; если вся серия проигрышная —
# переходим на следующую ступень. Любой выигрыш сбрасывает на первую ступень.
# Серия: [(ставка, сколько раз подряд), ...]
#   50 x 0.1  → если все 50 проиграли
#   5  x 1.0  → если все 5 проиграли
#   5  x 2.0  → если все 5 проиграли → возврат к 0.1
DEFAULT_BET_STRATEGY = [
    (0.1, 50),
    (1.0, 5),
    (2.0, 5),
]

# ---- Распознавание результата по цвету ----
# После клика уровня бот считывает пиксель в точке распознавания и
# сравнивает с эталонными цветами выигрыша/проигрыша (hex, #RRGGBB).
# Допуск — на сколько каждый канал (R/G/B) может отличаться от эталона,
# чтобы считать цвет совпавшим.
DEFAULT_WIN_COLOR = "#00ff00"   # цвет выигрыша
DEFAULT_LOSE_COLOR = "#ff0000"  # цвет проигрыша
DEFAULT_COLOR_TOLERANCE = 30    # допуск на канал (0..255)

# Пауза после клика, прежде чем читать цвет результата (сек)
DEFAULT_RESULT_DELAY = 0.4

# Пауза после проигрыша, прежде чем сделать следующую ставку той же серии (сек)
DEFAULT_LOSE_PAUSE = 1.0

# Горячая клавиша по умолчанию (вкл/выкл)
DEFAULT_HOTKEY = "f8"

# Настройки по умолчанию
DEFAULT_SETTINGS = {
    "rest_after_collect": 30,   # отдых после забора денег, секунды
    "line": LINE_MANUAL,        # выбранная линия
    "max_level": 12,            # до какого лвла доходить
    "collect_level": 12,        # на каком лвле забирать деньги
    "hotkey": DEFAULT_HOTKEY,
    "step_delay": DEFAULT_STEP_DELAY,
    # стратегия ставок: список [ставка, раз]
    "bet_strategy": DEFAULT_BET_STRATEGY,
    # распознавание результата по цвету
    "win_color": DEFAULT_WIN_COLOR,
    "lose_color": DEFAULT_LOSE_COLOR,
    "color_tolerance": DEFAULT_COLOR_TOLERANCE,
    "result_delay": DEFAULT_RESULT_DELAY,
    "lose_pause": DEFAULT_LOSE_PAUSE,
}


def level_info(level: int):
    """Возвращает (кэф, ячейки) для уровня."""
    return LEVELS.get(level, (1.0, 1))


def total_multiplier(max_level: int) -> float:
    """Суммарный кэф от 1 до max_level (произведение кэфов)."""
    m = 1.0
    for lv in range(1, max_level + 1):
        m *= LEVELS[lv][0]
    return round(m, 2)